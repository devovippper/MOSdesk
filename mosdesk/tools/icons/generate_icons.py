#!/usr/bin/env python3
"""Generate mosWM/file_icon_data.h (64x64 palette+RLE pixel-art icons).

    python3 mosdesk/tools/icons/generate_icons.py [--sheet preview.png]
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from PIL import Image
import icons

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
OUT = os.path.join(ROOT, 'mosWM', 'file_icon_data.h')
SVG = os.path.join(ROOT, 'mosdesk', 'icons', 'file-icons.svg')
PNG_DIR = os.path.join(ROOT, 'mosdesk', 'icons', 'pixel')
ALIASES = {'palette': 'APPEARANCE'}   # extra symbol ids used by preview.html

def encode(img):
    px = img.load()
    palette = [0]                     # index 0 = fully transparent
    index = {}
    idx = []
    for y in range(64):
        for x in range(64):
            r, g, b, a = px[x, y]
            if a == 0:
                idx.append(0); continue
            key = (a << 24) | (r << 16) | (g << 8) | b
            if key not in index:
                index[key] = len(palette); palette.append(key)
            idx.append(index[key])
    assert len(palette) <= 256, len(palette)
    runs = []
    i = 0
    while i < len(idx):
        j = i
        while j < len(idx) and idx[j] == idx[i] and j - i < 255: j += 1
        runs += [j - i, idx[i]]
        i = j
    return palette, runs

def fmt(values, per_line, hexa=False):
    lines = []
    for i in range(0, len(values), per_line):
        chunk = values[i:i + per_line]
        lines.append('    ' + ', '.join(('0x%08Xu' % v) if hexa else str(v) for v in chunk))
    return ',\n'.join(lines)

def write_web_assets():
    """PNG files + an SVG <symbol> sprite so preview.html shows the same art."""
    import base64, io
    os.makedirs(PNG_DIR, exist_ok=True)
    syms = []
    for name, fn in icons.ICONS:
        img = fn().img
        img.save(os.path.join(PNG_DIR, name.lower() + '.png'))
        buf = io.BytesIO(); img.save(buf, 'PNG', optimize=True)
        data = base64.b64encode(buf.getvalue()).decode()
        ids = [name.lower()] + [a for a, t in ALIASES.items() if t == name]
        for i in ids:
            syms.append('  <symbol id="%s" viewBox="0 0 64 64">\n    <image width="64" height="64" image-rendering="pixelated" href="data:image/png;base64,%s"/>\n  </symbol>' % (i, data))
    open(SVG, 'w').write('<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n' + '\n'.join(syms) + '\n</svg>\n')
    print('wrote', SVG, 'and', len(icons.ICONS), 'PNGs in', PNG_DIR)

def main():
    sheet = None
    if '--sheet' in sys.argv: sheet = sys.argv[sys.argv.index('--sheet') + 1]
    out = ['/* GENERATED by mosdesk/tools/icons/generate_icons.py -- do not edit.',
           ' * 64x64 pixel-art icons: ARGB palette + run-length (count, index) pairs. */',
           '#ifndef MOSWM_FILE_ICON_DATA_H', '#define MOSWM_FILE_ICON_DATA_H', '',
           '#include <stdint.h>', '']
    names = []
    total = 0
    for n, (name, fn) in enumerate(icons.ICONS):
        img = fn().img
        pal, runs = encode(img)
        total += len(runs) + len(pal) * 4
        out.append('static const uint32_t moswm_icon_%d_palette[%d] = { /* %s */\n%s\n};' % (n, len(pal), name, fmt(pal, 6, True)))
        out.append('static const uint8_t moswm_icon_%d_runs[%d] = {\n%s\n};' % (n, len(runs), fmt(runs, 24)))
        names.append((n, len(pal), len(runs)))
    out.append('\nstatic const struct {\n    const uint32_t* palette;\n    const uint8_t* runs;\n    uint32_t run_bytes;\n} moswm_icon_table[] = {')
    for n, pl, rl in names:
        out.append('    { moswm_icon_%d_palette, moswm_icon_%d_runs, %d },' % (n, n, rl))
    out.append('};\n\n#endif\n')
    open(OUT, 'w').write('\n'.join(out))
    write_web_assets()
    print('wrote', OUT, '(%d icons, ~%d bytes of data)' % (len(names), total))

if __name__ == '__main__':
    main()
